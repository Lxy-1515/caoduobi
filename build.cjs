const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
// Embed optional local audio or generated silence; no external media is distributed.
const audioFiles={music:'disco-bass-loop.wav',collect:'score-pickup.wav',ghost:'bubble-pop.wav',end:'game-end.wav',click:'menu-click.mp3'};
Object.assign(audioFiles,{"shop1":"shop-sound-1.wav","shop2":"shop-sound-2.wav","shop4":"shop-sound-4.wav","shop5":"shop-sound-5.wav","shop6":"shop-sound-6.wav","shop7":"shop-sound-7.wav","musicLemon":"shop-music-1.wav","musicFart":"shop-music-2.wav"});
// External audio is excluded. Generate 100ms mono silence for absent local files.
const rate=8000,frames=800,pcm=Buffer.alloc(44+frames*2);
pcm.write('RIFF',0);pcm.writeUInt32LE(pcm.length-8,4);pcm.write('WAVE',8);
pcm.write('fmt ',12);pcm.writeUInt32LE(16,16);pcm.writeUInt16LE(1,20);
pcm.writeUInt16LE(1,22);pcm.writeUInt32LE(rate,24);pcm.writeUInt32LE(rate*2,28);
pcm.writeUInt16LE(2,32);pcm.writeUInt16LE(16,34);pcm.write('data',36);pcm.writeUInt32LE(frames*2,40);
const audioData=Object.fromEntries(Object.entries(audioFiles).map(([key,file])=>{
 const local=path.join(root,'assets/audio',file);
 return[key,(fs.existsSync(local)?fs.readFileSync(local):pcm).toString('base64')];
}));
const audioScript='// Generated by build.cjs: optional local audio or silent placeholders.\n(function(P){P.audioAssets=Object.freeze('+JSON.stringify(audioData)+');})(globalThis.PixelDodge=globalThis.PixelDodge||{});\n';
fs.writeFileSync(path.join(root,'src/audio-assets.js'),audioScript,'utf8');
let html = read('index.html').replace('<link rel="stylesheet" href="style.css">', '<style>\n' + read('style.css') + '\n</style>');
html = html.replace(/\s*<script defer src="src\/[^"]+"><\/script>/g, '');
const scripts = ['content', 'store', 'achievements', 'achievements-view', 'geometry', 'twin-orbit', 'engine', 'render', 'mode-preview', 'audio-assets', 'audio', 'transition', 'title-glyphs', 'title', 'orientation', 'touch-controls', 'home-mask', 'result-presentation', 'shop', 'platform-config', 'leaderboards', 'rewarded-ads', 'ranking-view', 'app'].map(name => '<script>\n' + read('src/' + name + '.js').replace(/<\/script/gi, '<\\/script') + '\n</script>').join('\n');
html = html.replace('</body>', scripts + '\n</body>');
fs.writeFileSync(path.join(root, 'play.html'), html, 'utf8');
console.log('已生成可直接打开的单文件：play.html');
